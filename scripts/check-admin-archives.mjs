import assert from 'node:assert/strict';
import { createReviewFixture } from './check-reviews.mjs';
import { applyLocalArchives, changeArchive, matchesArchive } from '../src/lib/admin-archives.js';

const { db, call, customerCookie, adminCookie } = await createReviewFixture();
const owner = adminCookie(), alice = customerCookie('alice'), demo = adminCookie('demo');
const archive = (entity, id, archived, cookie = owner) => call(`admin/${entity}/${encodeURIComponent(id)}/archive`, 'PATCH', { archived }, cookie);
assert.equal((await archive('orders', 'paid-order', true, '')).status, 401);
assert.equal((await archive('orders', 'paid-order', true, alice)).status, 401);
assert.equal((await archive('orders', 'paid-order', true, demo)).status, 403);
assert.equal((await archive('customers', 'alice@example.com', true, demo)).status, 403);
assert.equal((await call('admin/customers', 'GET', null, alice)).status, 401);
assert.equal((await call('admin/orders/paid-order/archive', 'PATCH', { archived: 'yes' }, owner)).status, 400);
assert.equal((await archive('orders', 'missing-order', true)).status, 404);
const before = db.prepare("SELECT * FROM orders WHERE id = 'paid-order'").get();
await call('customer/reviews', 'POST', { orderId: 'paid-order', productId: 'p1', rating: 5, comment: 'Gostei muito da compra e do atendimento.', publicConsent: true }, alice);
const review = db.prepare('SELECT * FROM product_reviews').get();
await call(`admin/reviews/${review.id}`, 'PATCH', { status: 'approved' }, owner);
assert.equal((await archive('orders', 'paid-order', true)).status, 200);
const after = db.prepare("SELECT * FROM orders WHERE id = 'paid-order'").get();
assert.ok(after.archived_at);
assert.deepEqual({ ...after, archived_at: null }, { ...before, archived_at: null }, 'Só a coluna de arquivamento muda');
assert.ok(!(await call('admin/orders', 'GET', null, owner)).body.orders.some((row) => row.id === 'paid-order'));
assert.deepEqual((await call('admin/orders?archive=archived', 'GET', null, owner)).body.orders.map((row) => row.id), ['paid-order']);
assert.equal((await call('admin/orders?archive=all', 'GET', null, owner)).body.orders.length, 4);
assert.ok((await call('customer/orders', 'GET', null, alice)).body.orders.some((row) => row.id === 'paid-order'));
assert.equal((await call('reviews')).body.reviews.length, 1, 'Depoimento permanece publicado');
assert.equal((await archive('orders', 'paid-order', false)).status, 200);
assert.ok((await call('admin/orders', 'GET', null, owner)).body.orders.some((row) => row.id === 'paid-order'));

let customers = (await call('admin/customers', 'GET', null, owner)).body;
assert.equal(customers.total, 2);
assert.deepEqual(customers.summary, { total: 2, active: 2, archived: 0 });
assert.ok(customers.customers.every((row) => !('password_hash' in row) && !('password_salt' in row)));
assert.equal(customers.customers.find((row) => row.email === 'alice@example.com').order_count, 3);
const customerBefore = db.prepare("SELECT * FROM customers WHERE email = 'alice@example.com'").get();
assert.equal((await archive('customers', 'alice@example.com', true)).status, 200);
const customerAfter = db.prepare("SELECT * FROM customers WHERE email = 'alice@example.com'").get();
assert.deepEqual({ ...customerAfter, archived_at: null }, { ...customerBefore, archived_at: null });
assert.equal((await call('admin/customers', 'GET', null, owner)).body.total, 1);
assert.equal((await call('admin/customers?archive=archived&search=Alice', 'GET', null, owner)).body.total, 1);
assert.deepEqual((await call('admin/customers?archive=archived&search=Alice', 'GET', null, owner)).body.summary, { total: 2, active: 1, archived: 1 }, 'Filtros não escondem a contagem total da base');
assert.equal((await call('admin/customers?archive=all', 'GET', null, owner)).body.total, 2);
assert.equal((await call('customer/session', 'GET', null, alice)).status, 200);
assert.equal((await call('customer/profile', 'GET', null, alice)).status, 200);
assert.equal((await call('customer/orders', 'GET', null, alice)).body.orders.length, 3);
assert.equal((await archive('customers', 'alice@example.com', false)).status, 200);
assert.equal((await call('admin/customers', 'GET', null, owner)).body.total, 2);
assert.equal((await call('admin/customers?search=%27%20OR%201=1--', 'GET', null, owner)).body.total, 0);
assert.equal((await call('admin/customers?offset=50', 'GET', null, owner)).body.customers.length, 0);

const local = new Map();
globalThis.localStorage = { getItem: (key) => local.get(key) || null, setItem: (key, value) => local.set(key, value) };
globalThis.window = { dispatchEvent() {} };
await changeArchive('orders', 'paid-order', true, true);
assert.equal(matchesArchive(applyLocalArchives([{ id: 'paid-order' }], 'orders')[0]), false);
assert.equal(matchesArchive(applyLocalArchives([{ id: 'paid-order' }], 'orders')[0], 'archived'), true);
await changeArchive('orders', 'paid-order', false, true);
assert.equal(matchesArchive(applyLocalArchives([{ id: 'paid-order' }], 'orders')[0]), true);
await changeArchive('customers', 'alice@example.com', true, true);
assert.equal(matchesArchive(applyLocalArchives([{ email: 'alice@example.com' }], 'customers')[0]), false);
assert.equal(db.prepare("SELECT archived_at FROM customers WHERE email = 'alice@example.com'").get().archived_at, null, 'Demonstração não escreve no banco');
db.close();
console.log('OK: arquivar/restaurar pedidos e clientes, filtros, autenticação, isolamento demo, histórico, avaliações, pagamentos, estoque e credenciais preservados.');
