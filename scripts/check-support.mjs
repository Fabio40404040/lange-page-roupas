import assert from 'node:assert/strict';
import { createReviewFixture } from './check-reviews.mjs';
const { db, env, call, adminCookie, customerCookie } = await createReviewFixture();
env.DB.batch = async (statements) => {
  db.exec('BEGIN'); try { const results=[]; for (const stmt of statements) results.push(await stmt.run()); db.exec('COMMIT'); return results; } catch(error) { db.exec('ROLLBACK'); throw error; }
};
const alice=customerCookie('alice'), bob=customerCookie('bob'), owner=adminCookie(), demo=adminCookie('demo');
assert.equal((await call('customer/support')).status,401);
assert.equal((await call('admin/support')).status,401);
assert.equal((await call('admin/support','GET',null,demo)).status,403);
assert.deepEqual((await call('customer/support','GET',null,alice)).body.messages,[]);
assert.equal((await call('customer/support','POST',{message:'  '},alice)).status,400);
assert.equal((await call('customer/support','POST',{message:'a'.repeat(2001)},alice)).status,400);
let sent=await call('customer/support','POST',{message:'Olá! Quero saber sobre minha entrega.',customer_email:'bob@example.com',sender_role:'admin'},alice);
assert.equal(sent.status,201); const id=sent.body.threadId;
assert.equal((await call('customer/support','GET',null,bob)).body.thread,null);
assert.equal((await call(`customer/support/${id}`,'GET',null,bob)).status,404);
let listing=(await call('admin/support?status=unread','GET',null,owner)).body.threads;
assert.equal(listing.length,1); assert.equal(listing[0].customer_email,'alice@example.com'); assert.equal(listing[0].unread_count,1);
let events=(await call('admin/notifications','GET',null,owner)).body.events;
assert.ok(events.some(e=>e.kind==='support'&&e.threadId===id));
let conversation=(await call(`admin/support/${id}`,'GET',null,owner)).body;
assert.equal(conversation.messages[0].sender_role,'customer');
assert.equal((await call(`admin/support/${id}/read`,'POST',{throughId:conversation.messages.at(-1).id},owner)).status,200);
assert.equal((await call('admin/support?status=unread','GET',null,owner)).body.threads.length,0);
assert.equal((await call(`admin/support/${id}`,'POST',{message:'Olá! Vamos ajudar com o pedido.'},demo)).status,403);
assert.equal((await call(`admin/support/${id}`,'POST',{message:'Olá! Vamos ajudar com o pedido.'},owner)).status,201);
events=(await call('customer/notifications','GET',null,alice)).body.events;
assert.ok(events.some(e=>e.kind==='support'));
assert.ok(!(await call('customer/notifications','GET',null,bob)).body.events.some(e=>e.kind==='support'));
conversation=(await call('customer/support','GET',null,alice)).body;
const readThrough=conversation.messages.at(-1).id;
assert.equal(conversation.messages.length,2);
assert.equal((await call('customer/support/read','POST',{throughId:readThrough},alice)).status,200);
assert.ok(!(await call('customer/notifications','GET',null,alice)).body.events.some(e=>e.kind==='support'));
// Uma resposta nova posterior à leitura antiga continua não lida.
await call(`admin/support/${id}`,'POST',{message:'Seu pedido está sendo preparado.'},owner);
await call('customer/support/read','POST',{throughId:readThrough},alice);
assert.ok((await call('customer/notifications','GET',null,alice)).body.events.some(e=>e.kind==='support'));
assert.equal((await call(`admin/support/${id}/status`,'PATCH',{status:'resolved'},owner)).status,200);
assert.equal((await call('admin/support?status=resolved','GET',null,owner)).body.threads.length,1);
await call('customer/support','POST',{message:'Obrigada, tenho mais uma dúvida.'},alice);
assert.equal((await call('customer/support','GET',null,alice)).body.thread.status,'open');
const exported=(await call('customer/privacy-export','GET',null,alice)).body;
assert.equal(exported.support.length,4);
assert.equal((await call('customer/privacy-export','GET',null,bob)).body.support.length,0);
// Histórico paginado, sem perder mensagens antigas ou repetir a fronteira.
for(let n=0;n<60;n++) db.prepare('INSERT INTO support_messages(thread_id,sender_role,body,created_at) VALUES (?,?,?,?)').run(id,'admin',`Resposta ${n}`,new Date().toISOString());
const recent=(await call('customer/support','GET',null,alice)).body;
assert.equal(recent.messages.length,50); assert.equal(recent.hasMore,true);
const old=(await call(`customer/support?before=${recent.messages[0].id}`,'GET',null,alice)).body;
assert.equal(old.messages.length,14); assert.equal(old.hasMore,false);
assert.ok(old.messages.at(-1).id<recent.messages[0].id);
const inserted=db.prepare('SELECT count(*) AS count FROM support_messages').get().count;
assert.equal((await call('customer/support','POST',{message:'x'.repeat(2001)},alice)).status,400);
assert.equal(db.prepare('SELECT count(*) AS count FROM support_messages').get().count,inserted);
for (let i=0;i<8;i++) assert.equal((await call('customer/support','POST',{message:`Mensagem ${i}`},alice)).status,201);
assert.equal((await call('customer/support','POST',{message:'Mensagem excedente'},alice)).status,429);
console.log('OK: suporte autenticado cliente/admin, isolamento entre contas, aviso/leitura sem perder resposta nova, resolver/reabrir, paginação e exportação privada; demo bloqueada no backend.');
db.close();
